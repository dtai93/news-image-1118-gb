def _xy(lon, lat, w, h):
    return ((lon + 180.0) / 360.0 * (w - 1), (75.0 - lat) / 131.0 * (h - 1))


def paint_land(base, box):
    """Fill box with sea and land. 75N is the top edge, 56S the bottom."""
    x, y, w, h = (int(round(v)) for v in box)
    im = Image.new("RGB", (w, h), SEA)
    d = ImageDraw.Draw(im)
    for poly in polygons():
        pts = [_xy(lon, lat, w, h) for lon, lat in poly]
        if len(pts) >= 3:
            d.polygon(pts, fill=LANDC)
            d.line(pts + [pts[0]], fill=COAST, width=1)
    base.paste(im, (x, y))
    return (x, y, w, h)
